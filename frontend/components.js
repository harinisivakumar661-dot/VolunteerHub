// ===== Capacity bar =====
export function capacityBar(registered, capacity) {
  const pct = capacity > 0 ? Math.min(100, (registered / capacity) * 100) : 0
  const barCls = pct >= 100 ? 'cap-full' : pct >= 75 ? 'cap-high' : 'cap-normal'
  return `
    <div class="capacity-bar-wrap">
      <div class="capacity-bar-info">
        <span class="cap-count">${registered} / ${capacity}</span>
        <span class="cap-pct">${Math.round(pct)}%</span>
      </div>
      <div class="capacity-bar-track">
        <div class="capacity-bar-fill ${barCls}" style="width:${pct}%"></div>
      </div>
    </div>
  `
}

// ===== Format helpers =====
export function formatDate(dateStr) {
  if (!dateStr) return '-'
  const d = new Date(dateStr)
  if (isNaN(d.getTime())) return dateStr
  return d.toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' })
}

export function formatDateTime(dateStr) {
  if (!dateStr) return '-'
  const d = new Date(dateStr)
  if (isNaN(d.getTime())) return dateStr
  return d.toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' }) +
    ' ' + d.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' })
}

export function formatTimeAgo(dateStr) {
  if (!dateStr) return ''
  const d = new Date(dateStr)
  if (isNaN(d.getTime())) return ''
  const diff = Date.now() - d.getTime()
  const mins = Math.floor(diff / 60000)
  const hrs = Math.floor(diff / 3600000)
  const days = Math.floor(diff / 86400000)
  if (mins < 1) return 'just now'
  if (mins < 60) return `${mins}m ago`
  if (hrs < 24) return `${hrs}h ago`
  if (days < 7) return `${days}d ago`
  return formatDate(dateStr)
}

export function todayLong() {
  return new Date().toLocaleDateString('en-US', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' })
}

export function todayShort() {
  return new Date().toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })
}

// ===== Escape HTML =====
export function esc(str) {
  if (str === null || str === undefined) return ''
  return String(str).replace(/[&<>"']/g, (c) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
  }[c]))
}

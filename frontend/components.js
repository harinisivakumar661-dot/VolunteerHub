// ===== Toast =====
export function showToast(message, type = 'success') {
  const container = document.getElementById('toast-container')
  const toast = document.createElement('div')
  toast.className = `toast toast-${type}`
  const iconName = type === 'success' ? 'check' : type === 'error' ? 'alert' : 'info'
  toast.innerHTML = `
    <span class="toast-icon-wrap">${icon(iconName)}</span>
    <span class="toast-message">${message}</span>
    <button class="toast-close">${icons.x}</button>
  `
  toast.querySelector('.toast-close').addEventListener('click', () => toast.remove())
  container.appendChild(toast)
  requestAnimationFrame(() => toast.classList.add('toast-show'))
  setTimeout(() => {
    toast.classList.remove('toast-show')
    setTimeout(() => toast.remove(), 300)
  }, 4500)
}

// ===== Modal =====
export function openModal(title, bodyHtml, options = {}) {
  const overlay = document.getElementById('modal-overlay')
  const titleEl = document.getElementById('modal-title')
  const bodyEl = document.getElementById('modal-body')
  const footerEl = document.getElementById('modal-footer')
  const iconEl = document.getElementById('modal-icon')

  titleEl.textContent = title
  bodyEl.innerHTML = bodyHtml

  if (options.icon) {
    iconEl.innerHTML = icon(options.icon)
    iconEl.style.display = 'flex'
  } else {
    iconEl.innerHTML = ''
    iconEl.style.display = 'none'
  }

  if (options.footerHtml) {
    footerEl.innerHTML = options.footerHtml
    footerEl.style.display = 'flex'
  } else {
    footerEl.innerHTML = ''
    footerEl.style.display = 'none'
  }

  overlay.classList.add('modal-show')
  return overlay
}

export function closeModal() {
  const overlay = document.getElementById('modal-overlay')
  overlay.classList.remove('modal-show')
}

// ===== Skeleton loader =====
export function skeletonRows(cols = 5, rows = 5) {
  let rowsHtml = ''
  for (let i = 0; i < rows; i++) {
    let cells = ''
    for (let j = 0; j < cols; j++) {
      cells += `<td><div class="skeleton-line" style="width:${60 + Math.random() * 30}%"></div></td>`
    }
    rowsHtml += `<tr>${cells}</tr>`
  }
  return `<div class="table-wrapper"><table class="data-table"><tbody>${rowsHtml}</tbody></table></div>`
}


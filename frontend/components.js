// ===== Status badges =====
export function statusBadge(status) {
  const s = (status || '').toUpperCase()
  const cls =
    s === 'REGISTERED' ? 'badge-blue' :
    s === 'CANCELLED' ? 'badge-red' :
    s === 'ATTENDED' ? 'badge-green' :
    'badge-gray'
  return `<span class="status-badge ${cls}">${s}</span>`
}

export function eventStatusBadge(event) {
  const registered = getRegisteredCountGlobal(event)
  const capacity = event.capacity || 0
  const eventDate = new Date(event.date || event.eventDate || 0)
  const now = new Date()

  let label, cls
  if (registered >= capacity && capacity > 0) {
    label = 'FULL'; cls = 'badge-red'
  } else if (eventDate < now && eventDate.getTime() > 0) {
    label = 'COMPLETED'; cls = 'badge-gray'
  } else {
    label = 'UPCOMING'; cls = 'badge-blue'
  }
  return `<span class="status-badge ${cls}">${label}</span>`
}

